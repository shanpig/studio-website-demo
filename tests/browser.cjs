const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{})});
 const errors=[];fs.mkdirSync('screenshots',{recursive:true});
 try {
  const desktop=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true,deviceScaleFactor:1});
  desktop.on('pageerror',e=>errors.push('desktop: '+e.message));
  await desktop.goto('file://'+path.resolve('index.html'));
  await desktop.waitForFunction(()=>document.querySelector('#speechMode')?.textContent==='READY');
  assert.equal(await desktop.locator('.conversation').count(),0,'fixed bottom chat should no longer exist');
  assert(await desktop.locator('#speechPanel').isVisible(),'mascot must speak via nearby text');
  assert.equal(await desktop.locator('.hud-panel:not(.hidden)').count(),0,'idle must not show tool windows');
  assert(await desktop.locator('#speechText').innerText().then(s=>s.includes('有譜')),'first greeting missing');
  const core=await desktop.locator('#mascot').boundingBox();
  assert(core,'mascot not rendered');assert(Math.abs(core.x+core.width/2-720)<35,'mascot not centered');assert(core.width>=380,'central mascot too small');
  const caption=await desktop.locator('.core-caption').boundingBox(),speechLabel=await desktop.locator('.speech-label').boundingBox();
  assert(caption&&speechLabel&&caption.y+caption.height<speechLabel.y-8,'projected speech overlaps mascot identity');
  await desktop.screenshot({path:'screenshots/desktop-idle.png',fullPage:true});
  // A click on the mascot is an action: visible speaking effects plus projected text.
  await desktop.locator('#coreTrigger').click();
  assert(await desktop.locator('.hero-stage.is-speaking').count()===1,'mascot should animate while speaking');
  await desktop.waitForTimeout(420);
  const textDuring=await desktop.locator('#speechText').innerText();
  assert(textDuring.length>=2,'projected text should progressively appear');
  await desktop.screenshot({path:'screenshots/desktop-speaking.png',fullPage:true});
  await desktop.waitForFunction(()=>document.querySelector('#speechMode')?.textContent==='READY');
  // Optical gaze follows mouse rather than only moving vertically.
  await desktop.mouse.move(1050,290);
  await desktop.waitForTimeout(150);
  const gaze=await desktop.locator('#mascot').evaluate(el=>el.style.getPropertyValue('--gaze-x'));
  assert(gaze&&gaze!=='0.0px','optical gaze should track user movement');
  await desktop.locator('#historyToggle').click();
  assert(await desktop.locator('#historyPanel').isVisible(),'transcript drawer should open');
  assert(await desktop.locator('.msg.assistant').count()>0,'conversation history missing');
  await desktop.locator('#historyClose').click();
  assert(await desktop.locator('#historyPanel').isHidden(),'transcript drawer should close');
  await desktop.getByRole('button',{name:'開始規劃我的網站'}).click();
  for(let step=0;step<5;step++){
   const wizard=desktop.locator('.hud-panel[data-mode="wizard"]');
   assert(await wizard.isVisible(),'wizard must be visible at step '+step);
   await wizard.locator('.choice').first().click();
   await wizard.locator('.panel-btn.primary').click();
  }
  const style=desktop.locator('.hud-panel[data-mode="styles"]');
  assert(await style.isVisible(),'style explorer must appear after discovery');
  await style.locator('.style').nth(1).click();
  await style.locator('.panel-btn.primary').click();
  const review=desktop.locator('.hud-panel[data-mode="review"]');
  assert(await review.isVisible(),'review window must appear');
  await review.locator('button[type="submit"]').click();
  assert.equal(await review.locator('.review-item').count(),1,'one review item expected');
  await review.locator('.panel-btn').filter({hasText:'整理完整需求書'}).click();
  const brief=desktop.locator('.hud-panel[data-mode="brief"]');
  assert(await brief.isVisible(),'brief window must appear');
  const briefText=await brief.locator('.brief-preview').innerText();
  assert(briefText.includes('未來鋒芒'),'chosen style missing from brief');
  assert(briefText.includes('首頁主標題'),'review missing from brief');
  await desktop.waitForTimeout(500);
  await desktop.screenshot({path:'screenshots/desktop-flow.png',fullPage:true});
  const [dl]=await Promise.all([desktop.waitForEvent('download'),brief.locator('.panel-btn').filter({hasText:'下載需求書'}).click()]);
  assert(dl.suggestedFilename().endsWith('.txt'),'brief download missing');
  assert((await desktop.locator('.hud-panel:not(.hidden)').count())<=2,'too many active panels');
  await desktop.locator('#resetBtn').click();
  assert.equal(await desktop.locator('.hud-panel:not(.hidden)').count(),0,'reset failed to close tools');
  assert(await desktop.locator('#historyPanel').isHidden(),'history should be hidden on reset');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push('mobile: '+e.message));
  await mobile.goto('file://'+path.resolve('index.html'));
  await mobile.waitForFunction(()=>document.querySelector('#speechMode')?.textContent==='READY');
  assert(await mobile.locator('#speechPanel').isVisible(),'mobile projected conversation missing');
  await mobile.screenshot({path:'screenshots/mobile-idle.png',fullPage:true});
  await mobile.getByRole('button',{name:'先看設計範例'}).click();
  assert(await mobile.locator('.hud-panel[data-mode="styles"]').isVisible(),'mobile style tool not visible');
  const clipped=await mobile.locator('.hud-panel[data-mode="styles"] .hud-content').evaluate(el=>el.scrollHeight>el.clientHeight+3);
  assert(!clipped,'mobile panel content unexpectedly clipped');
  await mobile.waitForFunction(()=>document.querySelector('#speechMode')?.textContent==='READY');
  await mobile.screenshot({path:'screenshots/mobile-style.png',fullPage:true});
  assert((await mobile.locator('body').evaluate(x=>x.scrollWidth))<=395,'horizontal overflow');
  assert.deepEqual(errors,[],'runtime errors');
  console.log('PASS: mascot speaks from itself, active core/iris, history is optional, full guided journey, local export and mobile layout.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
