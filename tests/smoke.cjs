// Presence-first design checks. Chromium browser suite validates real user interactions.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8'),css=fs.readFileSync('hud.css','utf8'),js=fs.readFileSync('agent.js','utf8');
for(const name of ['index.html','hud.css','agent.js','favicon.svg','icon.svg'])assert(fs.existsSync(name),'missing '+name);
new vm.Script(js,{filename:'agent.js'});
assert(html.includes('lang="zh-Hant"')&&html.includes('name="viewport"'));
assert(html.includes('name="description"')&&html.includes('rel="icon"'));
assert(html.includes('href="#composer"')&&html.includes('id="composer"'));
assert(html.includes('id="mascot"')&&html.includes('id="coreTrigger"'));
assert(html.includes('id="speechText"')&&html.includes('id="speechAria"'));
assert(html.includes('id="speechMode"')&&html.includes('id="userEcho"'));
assert(html.includes('id="presenceWave"')&&html.includes('class="voice-rib r1"'));
assert(html.includes('id="historyToggle"')&&html.includes('id="historyPanel"'));
assert(!html.includes('class="conversation"'),'fixed bottom chat block should be removed');
assert(html.includes('data-jump="wizard"')&&html.includes('data-jump="styles"')&&html.includes('data-jump="review"')&&html.includes('data-jump="brief"'));
for(const mode of ['wizard','styles','review','brief'])assert(html.includes('data-mode="'+mode+'"'),'missing '+mode+' tool');
for(const fn of ['beginWizard','beginStyles','beginReview','beginBrief','download','reset','presentSpeech'])assert(js.includes('function '+fn+'('),'missing '+fn);
assert(js.includes("hero.classList.add('is-speaking')")&&js.includes("hero.classList.remove('is-speaking')"));
assert(js.includes('speechSequence')&&js.includes('requestAnimationFrame'));
assert(js.includes('setProperty(\'--gaze-x\''));
assert(js.includes('recentPanels.length>2')&&js.includes('URL.createObjectURL'));
assert(css.includes('prefers-reduced-motion')&&css.includes(':focus-visible'));
assert(css.includes('max-width:740px')&&css.includes('max-width:380px'));
assert(css.includes('.hero-stage.is-speaking .voice-rib'));
assert(!/\bfetch\s*\(|XMLHttpRequest|sendBeacon/.test(js),'unexpected data transfer');
const refs=[...js.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1]);const missing=[...new Set(refs)].filter(id=>!html.includes('id="'+id+'"'));
assert.deepEqual(missing,[],'missing ids '+missing.join(','));
console.log('PASS: no fixed chat, speaking core, text projection, history, four contextual tools, mobile and privacy');
