// Design companion smoke test — blocks broken static deployments, not a visual / accessibility audit.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8'),css=fs.readFileSync('hud.css','utf8'),js=fs.readFileSync('agent.js','utf8');
for(const name of ['index.html','hud.css','agent.js','favicon.svg','icon.svg'])assert(fs.existsSync(name),'missing '+name);
new vm.Script(js,{filename:'agent.js'});
assert(html.includes('lang="zh-Hant"')&&html.includes('name="viewport"'));
assert(html.includes('name="description"')&&html.includes('rel="icon"'));
assert(html.includes('href="#conversation"')&&html.includes('id="composer"'));
assert(html.includes('id="mascot"')&&html.includes('class="floating-core"'));
assert(html.includes('class="intro-copy"')&&html.includes('你的想法'));
assert(html.includes('data-jump="wizard"')&&html.includes('data-jump="styles"')&&html.includes('data-jump="review"')&&html.includes('data-jump="brief"'));
assert(html.includes('id="messages"')&&html.includes('aria-live="polite"'));
for(const mode of ['wizard','styles','review','brief'])assert(html.includes('data-mode="'+mode+'"'),'missing '+mode+' HUD window');
for(const fn of ['beginWizard','beginStyles','beginReview','beginBrief','download','reset'])assert(js.includes('function '+fn+'('),'missing '+fn);
assert(js.includes('recentPanels.length>2'),'too many simultaneous task windows allowed');
assert(js.includes('state.feedback')&&js.includes('URL.createObjectURL'));
assert(css.includes('prefers-reduced-motion')&&css.includes(':focus-visible'));
assert(css.includes('max-width:740px')&&css.includes('max-width:400px'));
assert(css.includes('--drag-x')&&js.includes("setProperty('--drag-x'"),'drag offset issue');
assert(!/\bfetch\s*\(|XMLHttpRequest|sendBeacon/.test(js),'unexpected network transfer');
const refs=[...js.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1]);const missing=[...new Set(refs)].filter(id=>!html.includes('id="'+id+'"'));
assert.deepEqual(missing,[],'missing DOM IDs: '+missing.join(','));
console.log('PASS: updated mascot, clear onboarding, four tools, two-panel limit, draggable panels, local export, responsive and basic a11y');
